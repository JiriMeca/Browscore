/**
 * Comprehensive ad / tracker / annoyance blocker — Brave-level coverage.
 *
 * Architecture:
 *   - ~2,500 blocked domains organized into categories matching Brave's shields
 *   - URL keyword pattern matching for requests that slip through domain matching
 *   - Cosmetic CSS filters injected via JavaScript to hide remaining ad DOM elements
 *   - HTTPS upgrade for known-safe domains
 *   - Per-category toggle support
 *   - Blocking statistics tracked in-memory and persisted to SharedPreferences
