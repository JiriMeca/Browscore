    // ==================== STATE ====================

    /** Total blocked requests counter (session lifetime). */
    private val _totalBlocked = AtomicLong(0)

    /** Per-category blocked counts. */
    private val _categoryBlocked = java.util.concurrent.ConcurrentHashMap<BlockCategory, AtomicLong>()

    /** Per-page cosmetic filter cache. */
    private val cosmeticFilterCache = object : LinkedHashMap<String, String>(50, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String>?): Boolean {
            return size > 50
        }
    }

    /** Small LRU cache (50 entries) of parsed host strings. */
    private val hostCache = object : LinkedHashMap<String, String>(50, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String>?): Boolean {
            return size > 50
        }
    }

    init {
        // Initialize per-category counters
        for (cat in BlockCategory.entries) {
            _categoryBlocked[cat] = AtomicLong(0)
        }
    }

    // ==================== PUBLIC API ====================

    /** Total blocked requests in the current session. */
    fun totalBlocked(): Long = _totalBlocked.get()

    /** Blocked count per category in the current session. */
    fun blockedByCategory(): Map<BlockCategory, Long> =
        BlockCategory.entries.associateWith { _categoryBlocked[it]?.get() ?: 0L }

    /** Reset all session statistics. */
    fun resetStats() {
        _totalBlocked.set(0)
        for (cat in BlockCategory.entries) {
            _categoryBlocked[cat]?.set(0)
        }
    }

    /** Whether the user has enabled the ad-blocker (default: true). */
    fun isEnabled(ctx: Context): Boolean = Prefs.getAdBlockEnabled(ctx)

    /** Check if a specific category is enabled. */
    fun isCategoryEnabled(ctx: Context, category: BlockCategory): Boolean {
        return Prefs.getAdBlockCategoryEnabled(ctx, category)
    }

    /**
     * Returns true if ad-blocking is enabled AND the URL matches a
     * blocked domain or URL pattern.
     */
    fun shouldBlock(ctx: Context, url: String): Boolean {
        if (!isEnabled(ctx)) return false
        if (isAd(url)) {
            _totalBlocked.incrementAndGet()
            return true
        }
        return false
    }

    /**
     * Convenience: checks [shouldBlock] for the given [WebResourceRequest].
     * Returns an empty response if blocked, or null if it should proceed normally.
     */
    fun interceptIfBlocked(ctx: Context, request: WebResourceRequest): WebResourceResponse? {
        // NEVER block main-frame navigations
        if (request.isForMainFrame) return null
        val url = request.url.toString()
        return if (shouldBlock(ctx, url)) emptyResponse() else null
    }

    /**
     * Returns true if the URL's host ends with (or equals) a blocked domain
     * OR matches a URL keyword pattern.
     */
    fun isAd(url: String): Boolean {
        val host = parseHost(url) ?: return false

        // Fast path: check each category's domain set
        for ((category, domains) in DOMAINS) {
            for (domain in domains) {
                if (host == domain || host.endsWith(".$domain")) {
                    _categoryBlocked[category]?.incrementAndGet()
                    return true
                }
            }
        }

        // Check URL keyword patterns
        val lowerUrl = url.lowercase()
        for (pattern in URL_PATTERNS) {
            if (lowerUrl.contains(pattern.lowercase())) {
                _categoryBlocked[BlockCategory.OTHER]?.incrementAndGet()
                return true
            }
        }

        return false
    }

    /**
     * Builds an empty [WebResourceResponse] used to silently drop an
     * ad/tracker request.
     */
    fun emptyResponse(): WebResourceResponse {
        return WebResourceResponse("text/plain", "utf-8", ByteArrayInputStream(ByteArray(0)))
    }

    /**
     * Returns JavaScript code to inject cosmetic CSS filters that hide
     * ad/tracker DOM elements. The result is cached per-page domain.
     */
    fun getCosmeticFilterJs(pageUrl: String): String {
        val domain = parseHost(pageUrl) ?: return ""
        return cosmeticFilterCache.getOrPut(domain) {
            buildCosmeticFilterJs()
        }
    }

    /**
     * Returns an HTTPS-upgraded URL if the domain is in our upgrade list.
     * Returns null if no upgrade is needed or the URL is already HTTPS.
     */
    fun upgradeToHttps(url: String): String? {
        if (url.startsWith("https://")) return null
        if (!url.startsWith("http://")) return null
        val host = parseHost(url) ?: return null
        for (httpsDomain in HTTPS_DOMAINS) {
            if (host == httpsDomain || host.endsWith(".$httpsDomain")) {
                return "https://${url.substring(7)}"
            }
        }
        return null
    }

    // ==================== INTERNAL ====================

    /** Parses the host from a URL string, using LRU cache. */
    private fun parseHost(url: String): String? {
        return hostCache.getOrPut(url) {
            try { Uri.parse(url).host ?: "" } catch (_: Exception) { "" }
        }.ifBlank { null }
    }

    /**
     * Builds the cosmetic filter JavaScript that creates a <style> element
     * with CSS rules to hide all matched ad/tracker DOM elements.
     */
    private fun buildCosmeticFilterJs(): String {
        val cssRules = COSMETIC_SELECTORS.joinToString(",\n") { "$it { display: none !important; visibility: hidden !important; height: 0 !important; min-height: 0 !important; max-height: 0 !important; overflow: hidden !important; pointer-events: none !important; }" }

        return """
        (function(){
            var id = '__pb_cosmetic_filter';
            if (document.getElementById(id)) return;
            var s = document.createElement('style');
            s.id = id;
            s.textContent = `$cssRules`;
            (document.head || document.documentElement).appendChild(s);
            // Re-apply periodically to catch dynamically injected ads
            var observer = new MutationObserver(function(mutations) {
                for (var i = 0; i < mutations.length; i++) {
                    for (var j = 0; j < mutations[i].addedNodes.length; j++) {
                        var node = mutations[i].addedNodes[j];
                        if (node.nodeType === 1) {
                            var selectors = `${COSMETIC_SELECTORS.joinToString(",")}`;
                            var matched = node.querySelectorAll ? node.querySelectorAll(selectors) : null;
                            if (matched && matched.length > 0) return;
                        }
                    }
                }
            });
            if (document.body) {
                observer.observe(document.body, { childList: true, subtree: true });
            } else {
                document.addEventListener('DOMContentLoaded', function() {
                    observer.observe(document.body, { childList: true, subtree: true });
                });
            }
            // Also apply on load
            if (document.readyState === 'complete' || document.readyState === 'interactive') {
                applySelectors();
            } else {
                window.addEventListener('load', applySelectors);
            }
            function applySelectors() {
                var all = document.querySelectorAll(`${COSMETIC_SELECTORS.joinToString(",")}`);
                for (var i = 0; i < all.length; i++) {
                    all[i].style.setProperty('display', 'none', 'important');
                }
            }
            // MutationObserver auto-applies via CSS rules
        })();
        """.trimIndent()
    }
